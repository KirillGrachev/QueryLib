package me.kirillgrachev.query.exec;

import java.sql.ResultSet;
import java.sql.SQLException;

/**
 * Преобразует текущую строку {@link ResultSet} в значение.
 *
 * <p>Курсор уже установлен на строке: вызывать {@code next()} не нужно и нельзя.
 *
 * <p>Возврат {@code null} допустим и означает «строки нет»: при маппинге одного
 * результата он превращается в пустой {@code Optional}, а при маппинге списка
 * элемент со значением {@code null} добавляется как есть. Такое поведение
 * зафиксировано тестами, потому что альтернатива — молча пропускать строки —
 * привела бы к расхождению числа строк в базе и в результате.
 *
 * @param <T> тип результата
 */
@FunctionalInterface
public interface RowMapper<T> {

    /**
     * Читает значение из текущей строки.
     *
     * @param rs result set, установленный на строку
     * @return значение, возможно {@code null}
     * @throws SQLException при ошибке чтения; не оборачивается, поскольку
     *                      является частью контракта JDBC и вызывающая сторона
     *                      всё равно получит его в обёртке библиотеки
     */
    T map(ResultSet rs) throws SQLException;

}
