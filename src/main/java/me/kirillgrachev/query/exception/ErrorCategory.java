package me.kirillgrachev.query.exception;

/**
 * Категория ошибки для быстрой маршрутировки.
 *
 * <p>Категория отвечает на вопрос «кто виноват», а не «что случилось». Это
 * принципиально для библиотеки, которую встраивают в чужой код: вызывающая
 * сторона должна уметь отличить свою ошибку (неверный идентификатор, неверное
 * число плейсхолдеров) от ошибки инфраструктуры (оборвалось соединение, драйвер
 * не поддерживает операцию) и от внутреннего сбоя библиотеки.
 *
 * <p>Разделение нужно ещё и потому, что реакции на категории разные:
 * {@link #VALIDATION} и {@link #SQL_GENERATION} — это дефект кода, их нельзя
 * перехватывать и «ретраить», их надо чинить; {@link #EXECUTION} и
 * {@link #RESOURCE} могут быть транзитными, и для них допустим повтор.
 */
public enum ErrorCategory {

    /** Входные данные отвергнуты до генерации SQL: идентификаторы, плейсхолдеры, аргументы билдера. */
    VALIDATION,

    /** SQL не может быть собран из корректных входных данных: пустой список колонок, несовместимые клаузы. */
    SQL_GENERATION,

    /** Ошибка на этапе исполнения: драйвер, соединение, ограничение СУБД, SQLException. */
    EXECUTION,

    /** Ошибка управления ресурсами: statement или result set не удалось закрыть. */
    RESOURCE,

    /** Внутренняя ошибка библиотеки, которой в нормальных условиях быть не должно. */
    SYSTEM

}
