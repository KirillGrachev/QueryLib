package me.kirillgrachev.query.sql;

import org.jetbrains.annotations.NotNull;

import java.util.List;

/**
 * Описание SQL-запроса, не зависящее от диалекта.
 *
 * <p>Запрос — это чистые данные: текст с плейсхолдерами и упорядоченный список
 * параметров. Исполнение вынесено в {@code Sql}, поэтому один и тот же объект
 * запроса можно рендерить в разные диалекты, логировать, сравнивать в тестах и
 * исполнять повторно, не опасаясь, что состояние изменилось.
 *
 * <p>Диалект передаётся в {@link #getSql(Dialect)}, а не хранится в запросе. Это
 * сознательное решение: запрос, знающий свой диалект, нельзя переиспользовать
 * между базами (например, при миграции с MySQL на PostgreSQL), а тесты вынуждены
 * были бы конструировать объект ради получения текста.
 *
 * <p>Метод назван {@code getSql}, а не {@code getSQL} как в исходной библиотеке:
 * аббревиатуры в именах методов пишутся по правилам camelCase, иначе
 * {@code getSQLStatement} и {@code getSqlStatement} начинают сосуществовать
 * в одном API.
 */
public interface SqlStatement {

    /**
     * Рендерит запрос в SQL для указанного диалекта.
     *
     * <p>Результат не содержит завершающей точки с запятой. В исходной библиотеке
     * все {@code getSQL()} добавляли {@code ;}, что ломало пакетное исполнение на
     * части драйверов и не давало использовать запрос как подвыражение; хуже того,
     * этот хвост был закреплён в тестах как эталон.
     *
     * @param dialect диалект, определяющий кавычки идентификаторов и синтаксис пагинации
     * @return текст SQL без завершающей точки с запятой
     * @throws me.kirillgrachev.query.exception.QueryException если запрос неполон
     */
    @NotNull String getSql(@NotNull Dialect dialect);

    /**
     * Возвращает параметры в порядке следования плейсхолдеров.
     *
     * <p>Список неизменяемый: вызывающая сторона не может поменять значения после
     * построения запроса. Исходная библиотека хранила массивы параметров по
     * ссылке, поэтому мутация массива клиентом меняла уже собранный запрос.
     *
     * <p>Элементы могут быть {@code null} — это SQL NULL, привязкой которого
     * занимается слой исполнения.
     *
     * @return неизменяемый список параметров, возможно пустой
     */
    @NotNull List<Object> getParams();

}
