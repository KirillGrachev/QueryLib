package me.kirillgrachev.query.sql;

import org.jetbrains.annotations.NotNull;

import java.util.List;

/**
 * Условие {@code WHERE} как композируемое дерево.
 *
 * <p>Исходная библиотека умела соединять условия только через {@code AND}:
 * любое {@code OR} и любая вложенность выражались исключительно сырым SQL через
 * {@code whereExpr}. Для библиотеки, чья заявленная цель — избавить от сырого SQL,
 * это означает, что самый частый после равенства случай ({@code OR}, группы
 * условий) остаётся не закрытым.
 *
 * <p>Дерево вместо плоского списка нужно ещё и по другой причине: смешивание
 * {@code AND} и {@code OR} без явных скобок — классический источник ошибок, где
 * {@code a AND b OR c} читается автором как {@code a AND (b OR c)}, а выполняется
 * как {@code (a AND b) OR c}. Композитный узел всегда рендерится в скобках,
 * поэтому приоритет определяется структурой дерева, а не памятью разработчика.
 *
 * <p>Реализация package-private: наружу отдаётся только этот интерфейс и фабрики
 * {@link Conditions}, чтобы способ рендеринга можно было изменить, не ломая API.
 */
public interface Condition {

    /**
     * Рендерит условие в SQL для диалекта.
     *
     * <p>Результат всегда заключён в скобки, если содержит несколько операндов,
     * поэтому вызывающая сторона может не заботиться о приоритетах.
     *
     * @param dialect диалект для экранирования идентификаторов
     * @return текст условия без ведущего {@code WHERE}
     */
    @NotNull String render(@NotNull Dialect dialect);

    /**
     * Возвращает параметры условия в порядке следования плейсхолдеров.
     *
     * <p>Порядок обязан совпадать с порядком плейсхолдеров в {@link #render(Dialect)}:
     * привязка параметров выполняется позиционно, и расхождение дало бы запрос,
     * который синтаксически корректен, но возвращает не те данные.
     *
     * @return неизменяемый список параметров
     */
    @NotNull List<Object> getParams();

}
