package me.kirillgrachev.query.exec;

import me.kirillgrachev.query.Query;
import me.kirillgrachev.query.exception.ErrorCode;
import me.kirillgrachev.query.exception.QueryException;
import me.kirillgrachev.query.sql.Dialect;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.sql.SQLException;
import java.sql.Statement;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Тесты {@link BatchExecutor} на настоящей базе.
 *
 * <p>Закрывают три дефекта исходного {@code BatchBuilder}: буфер не очищался
 * после исполнения (повторный вызов дублировал данные), размер пакета не
 * ограничивался, а результат {@code executeBatch()} возвращался сырым массивом,
 * в котором {@code SUCCESS_NO_INFO} ({@code -2}) делал сумму отрицательной.
 */
class BatchExecutorTest {

    private static final String DB_URL = "jdbc:h2:mem:batch_test;DB_CLOSE_DELAY=-1";

    private JdbcDataSource dataSource;
    private Sql sql;

    @BeforeEach
    void setUp() throws SQLException {

        dataSource = new JdbcDataSource();
        dataSource.setURL(DB_URL);
        sql = Sql.of(dataSource, Dialect.H2);

        try (Statement st = dataSource.getConnection().createStatement()) {
            st.execute("DROP TABLE IF EXISTS \"logs\"");
            st.execute("CREATE TABLE \"logs\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " \"level\" VARCHAR(16) NOT NULL, \"message\" VARCHAR(128) NOT NULL)");
        }

    }

    @Test
    void executesAllAddedStatements() {

        BatchExecutor batch = sql.batch();

        for (int i = 0; i < 100; i++) {
            batch.add(Query.insertInto("logs").value("level", "INFO").value("message", "m" + i));
        }

        BatchResult result = batch.execute();

        assertEquals(100, result.statementsExecuted());
        assertEquals(100L, countRows());

    }

    @Test
    void chunkingDoesNotChangeTheResult() {

        BatchExecutor batch = sql.batch().chunkSize(7);

        for (int i = 0; i < 50; i++) {
            batch.add(Query.insertInto("logs").value("level", "INFO").value("message", "c" + i));
        }

        BatchResult result = batch.execute();

        assertEquals(50, result.statementsExecuted());
        assertEquals(50L, countRows());

    }

    @Test
    void bufferIsClearedAfterExecution() {

        // Исходный BatchBuilder не очищался, и второй execute() отправлял все
        // предыдущие строки заново вместе с новыми.
        BatchExecutor batch = sql.batch();

        for (int i = 0; i < 10; i++) {
            batch.add(Query.insertInto("logs").value("level", "INFO").value("message", "first" + i));
        }

        batch.execute();
        assertEquals(0, batch.size(), "буфер должен быть пуст после исполнения");

        BatchResult second = batch.execute();

        assertEquals(0, second.statementsExecuted());
        assertEquals(10L, countRows(), "повторный execute не должен дублировать строки");

    }

    @Test
    void bufferIsClearedEvenWhenExecutionFails() {

        BatchExecutor batch = sql.batch();

        for (int i = 0; i < 5; i++) {
            batch.add(Query.insertInto("logs").value("level", "INFO").value("message", "ok" + i));
        }

        // message объявлен NOT NULL, поэтому строка с null нарушает ограничение
        // и весь пакет падает. Проверяется, что буфер очищен и после ошибки:
        // иначе повторный execute() отправил бы часть строк второй раз.
        BatchExecutor failing = sql.batch();

        for (int i = 0; i < 3; i++) {
            failing.add(Query.raw("INSERT INTO \"logs\" (\"level\", \"message\") VALUES (?, ?)", "INFO", "x" + i));
        }

        failing.add(Query.raw("INSERT INTO \"logs\" (\"level\", \"message\") VALUES (?, ?)", "INFO", null));

        assertEquals(4, failing.size());
        assertThrows(QueryException.class, failing::execute);
        assertEquals(0, failing.size(), "буфер должен очищаться и при ошибке исполнения");

    }

    @Test
    void clearDiscardsPendingStatements() {

        BatchExecutor batch = sql.batch();

        batch.add(Query.insertInto("logs").value("level", "INFO").value("message", "discarded"));
        assertEquals(1, batch.size());

        batch.clear();
        assertEquals(0, batch.size());

        BatchResult result = batch.execute();

        assertEquals(0, result.statementsExecuted());
        assertEquals(0L, countRows());

    }

    @Test
    void differingSqlIsRejected() {

        BatchExecutor batch = sql.batch();

        batch.add(Query.insertInto("logs").value("level", "INFO").value("message", "a"));

        QueryException e = assertThrows(QueryException.class,
                () -> batch.add(Query.insertInto("logs").value("level", "INFO")));

        assertEquals(ErrorCode.CONFLICTING_CLAUSES, e.getCode());
        assertTrue(e.getContext().containsKey("expected"));
        assertTrue(e.getContext().containsKey("actual"));

    }

    @Test
    void emptyBatchDoesNotTouchTheDatabase() {

        BatchResult result = sql.batch().execute();

        assertEquals(0, result.statementsExecuted());
        assertEquals(0L, result.rowsAffected());
        assertTrue(result.rawCounts().isEmpty());

    }

    @Test
    void rowCountIsReportedExplicitly() {

        BatchExecutor batch = sql.batch();

        for (int i = 0; i < 10; i++) {
            batch.add(Query.insertInto("logs").value("level", "INFO").value("message", "r" + i));
        }

        BatchResult result = batch.execute();

        // H2 возвращает точные счётчики, поэтому SUCCESS_NO_INFO не встречается.
        // На MySQL с rewriteBatchedStatements=true счётчики были бы неизвестны,
        // и тогда rowsAffected() нельзя сравнивать с числом строк — для этого
        // есть isRowCountExact().
        assertTrue(result.isRowCountExact(), "H2 должен возвращать точные счётчики");
        assertEquals(10L, result.rowsAffected());
        assertEquals(10L, result.effectiveRows());

    }

    @Test
    void invalidChunkSizeIsRejected() {
        QueryException e = assertThrows(QueryException.class, () -> sql.batch().chunkSize(0));
        assertEquals(ErrorCode.INVALID_ARGUMENT_VALUE, e.getCode());
    }

    @Test
    void batchInsideTransactionIsAtomic() {

        assertThrows(IllegalStateException.class, () -> sql.inTransaction(tx -> {
            BatchExecutor batch = tx.batch();

            for (int i = 0; i < 5; i++) {
                batch.add(Query.insertInto("logs").value("level", "INFO").value("message", "tx" + i));
            }

            batch.execute();

            throw new IllegalStateException("rollback the whole transaction");
        }));

        assertEquals(0L, countRows(), "пакет внутри транзакции должен откатываться вместе с ней");

    }

    private long countRows() {
        return sql.queryOne(Query.select().expr("COUNT(*)").from("logs"),
                rs -> rs.getLong(1)).orElseThrow();
    }

}
