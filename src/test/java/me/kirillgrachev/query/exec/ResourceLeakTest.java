package me.kirillgrachev.query.exec;

import me.kirillgrachev.query.Query;
import me.kirillgrachev.query.testsupport.CountingDataSource;
import me.kirillgrachev.query.sql.Dialect;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Доказательство отсутствия утечек JDBC-ресурсов.
 *
 * <p>Самый важный набор тестов библиотеки, потому что проверяет дефекты, которые
 * невозможно заметить по поведению: запросы работают, а падение наступает через
 * часы, когда число открытых курсоров упирается в лимит СУБД. В исходной
 * библиотеке таких утечек было три — {@code query(Connection)} и
 * {@code updateWithKeys(Connection)} теряли statement при исключении, а
 * {@code ResultSetWrapper.map()/mapAll()} не закрывали statement никогда, хотя
 * javadoc обещал обратное.
 *
 * <p>Подсчёт ведётся динамическим прокси на всех трёх уровнях (соединение,
 * statement, result set), поэтому тест ловит утечку любого из них.
 */
class ResourceLeakTest {

    private static final String DB_URL = "jdbc:h2:mem:leak_test;DB_CLOSE_DELAY=-1";

    private CountingDataSource counting;
    private Sql sql;

    @BeforeEach
    void setUp() throws SQLException {

        JdbcDataSource raw = new JdbcDataSource();
        raw.setURL(DB_URL);

        try (Statement st = raw.getConnection().createStatement()) {
            // Имена в DDL экранированы: H2 хранит неэкранированные имена в верхнем
            // регистре, а Dialect.H2 экранирует идентификаторы в запросах, поэтому
            // без кавычек здесь и там имена не совпали бы.
            st.execute("DROP TABLE IF EXISTS \"items\"");
            st.execute("CREATE TABLE \"items\" (\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    + " \"name\" VARCHAR(32) NOT NULL)");
            st.execute("INSERT INTO \"items\" (\"name\") VALUES ('a'), ('b'), ('c')");
        }

        counting = new CountingDataSource(raw);
        sql = Sql.of(counting, Dialect.H2);
        counting.reset();

    }

    @Test
    void queryAllClosesEveryResource() {

        for (int i = 0; i < 50; i++) {
            List<String> names = sql.queryAll(Query.select("name").from("items"),
                    rs -> rs.getString("name"));

            assertEquals(3, names.size());
        }

        assertNoLeaks();
        assertEquals(50, counting.getStatementsCreated());
        assertEquals(50, counting.getStatementsClosed());

    }

    @Test
    void queryOneClosesResultSetEvenThoughOnlyFirstRowIsRead() {

        // Чтение одной строки из трёх — самый частый случай утечки: result set
        // остаётся недочитанным, и закрыть его обязан вызывающий код библиотеки.
        for (int i = 0; i < 50; i++) {
            sql.queryOne(Query.select("name").from("items"), rs -> rs.getString("name"));
        }

        assertNoLeaks();
        assertEquals(50, counting.getResultSetsCreated());
        assertEquals(50, counting.getResultSetsClosed());

    }

    @Test
    void updateClosesStatement() {

        for (int i = 0; i < 30; i++) {
            sql.update(Query.update("items").value("name", "x").where("id", 1));
        }

        assertNoLeaks();
        assertEquals(30, counting.getStatementsCreated());
        assertEquals(30, counting.getStatementsClosed());

    }

    @Test
    void insertReturningKeyClosesBothStatementAndKeysResultSet() {

        for (int i = 0; i < 20; i++) {
            sql.insertReturningKey(Query.insertInto("items").value("name", "n" + i),
                    rs -> rs.getLong(1));
        }

        assertNoLeaks();
        // Один statement и один result set сгенерированных ключей на каждую вставку.
        assertEquals(20, counting.getStatementsCreated());
        assertEquals(20, counting.getStatementsClosed());
        assertEquals(20, counting.getResultSetsCreated());
        assertEquals(20, counting.getResultSetsClosed());

    }

    @Test
    void failingQueryDoesNotLeakStatement() {

        // Ключевая регрессия: в исходной библиотеке statement создавался вне
        // try-with-resources и передавался в обёртку уже ПОСЛЕ executeQuery,
        // поэтому исключение на исполнении оставляло его открытым навсегда.
        //
        // Ошибка нужна именно на стадии исполнения, а не подготовки: неверный SQL
        // отклоняется уже в prepareStatement, и тогда statement не создаётся вовсе.
        // CAST текста в INT проходит подготовку и падает на данных.
        for (int i = 0; i < 20; i++) {
            assertThrows(RuntimeException.class, () -> sql.queryAll(
                    Query.raw("SELECT CAST(\"name\" AS INT) FROM \"items\""),
                    rs -> rs.getInt(1)));
        }

        assertBalanced();
        assertEquals(20, counting.getStatementsCreated());
        assertEquals(20, counting.getStatementsClosed(),
                "statement должен закрываться и на пути через исключение");

    }

    @Test
    void failingUpdateDoesNotLeakStatement() {

        // Нарушение NOT NULL на первичном ключе: подготовка проходит, ошибка
        // возникает в executeUpdate.
        for (int i = 0; i < 20; i++) {
            assertThrows(RuntimeException.class,
                    () -> sql.update(Query.raw("UPDATE \"items\" SET \"id\" = NULL WHERE \"id\" = 1")));
        }

        assertBalanced();
        assertEquals(20, counting.getStatementsCreated());
        assertEquals(counting.getStatementsCreated(), counting.getStatementsClosed());

    }

    @Test
    void failingInsertReturningKeyDoesNotLeakStatement() {

        for (int i = 0; i < 20; i++) {
            assertThrows(RuntimeException.class,
                    () -> sql.insertReturningKey(
                            Query.raw("INSERT INTO \"items\" (\"name\") VALUES (NULL)"),
                            rs -> rs.getLong(1)));
        }

        assertBalanced();
        assertEquals(20, counting.getStatementsCreated());
        assertEquals(counting.getStatementsCreated(), counting.getStatementsClosed());

    }

    @Test
    void prepareFailureLeaksNothing() {

        // Отдельный сценарий: неверный SQL отклоняется в prepareStatement, поэтому
        // statement не создаётся вовсе. Здесь проверка иная — создано ноль и
        // закрыто ноль, и требовать «больше нуля» было бы неверно.
        for (int i = 0; i < 10; i++) {
            assertThrows(RuntimeException.class,
                    () -> sql.queryAll(Query.raw("SELECT * FROM no_such_table"), rs -> rs.getString(1)));
        }

        assertBalanced();
        assertEquals(0, counting.getStatementsCreated());
        assertEquals(0, counting.getStatementsClosed());

    }

    @Test
    void failingMapperDoesNotLeakResources() {

        for (int i = 0; i < 20; i++) {
            assertThrows(IllegalStateException.class, () -> sql.queryAll(
                    Query.select("name").from("items"),
                    rs -> {
                        throw new IllegalStateException("mapper failed");
                    }));
        }

        assertNoLeaks();

    }

    @Test
    void transactionClosesItsConnection() {

        sql.inTransaction(tx -> {
            tx.update(Query.update("items").value("name", "t").where("id", 1));
            tx.queryAll(Query.select("name").from("items"), rs -> rs.getString("name"));

            return null;
        });

        assertNoLeaks();
        assertEquals(1, counting.getConnectionsCreated(),
                "транзакция обязана использовать одно соединение на всё тело");
        assertEquals(1, counting.getConnectionsClosed());

    }

    @Test
    void failedTransactionStillClosesItsConnection() {

        assertThrows(IllegalStateException.class, () -> sql.inTransaction(tx -> {
            tx.update(Query.update("items").value("name", "t").where("id", 1));
            throw new IllegalStateException("rollback path");
        }));

        assertNoLeaks();
        assertEquals(1, counting.getConnectionsCreated());
        assertEquals(1, counting.getConnectionsClosed());

    }

    @Test
    void manyOperationsDoNotAccumulateResources() {

        // Практическая проверка сценария, при котором утечка и проявляется:
        // долгоживущее приложение выполняет тысячи запросов подряд.
        for (int i = 0; i < 500; i++) {
            sql.queryOne(Query.select("name").from("items").where("id", (i % 3) + 1),
                    rs -> rs.getString("name"));
        }

        assertNoLeaks();
        assertEquals(500, counting.getStatementsCreated());
        assertEquals(500, counting.getStatementsClosed());
        assertEquals(500, counting.getResultSetsCreated());
        assertEquals(500, counting.getResultSetsClosed());

    }

    /**
     * Проверяет баланс созданных и закрытых ресурсов.
     *
     * <p>Не требует, чтобы ресурсов было больше нуля: на сценарии ошибки в
     * prepareStatement их может не быть вовсе, и это корректный результат.
     * Требование «тест что-то создал» добавляется явно там, где проверяется
     * закрытие на успешном пути.
     */
    private void assertBalanced() {

        assertEquals(0, counting.getLeaks(),
                "обнаружена утечка: создано соединений=" + counting.getConnectionsCreated()
                        + " закрыто=" + counting.getConnectionsClosed()
                        + ", statement'ов создано=" + counting.getStatementsCreated()
                        + " закрыто=" + counting.getStatementsClosed()
                        + ", result set'ов создано=" + counting.getResultSetsCreated()
                        + " закрыто=" + counting.getResultSetsClosed());

    }

    private void assertNoLeaks() {
        assertBalanced();
        assertTrue(counting.getStatementsCreated() > 0, "тест не создал ни одного statement'а");
    }

}
