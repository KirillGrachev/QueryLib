package me.kirillgrachev.query.exec;

import me.kirillgrachev.query.Query;
import me.kirillgrachev.query.exception.ErrorCode;
import me.kirillgrachev.query.exception.QueryException;
import me.kirillgrachev.query.sql.Conditions;
import me.kirillgrachev.query.sql.Dialect;
import me.kirillgrachev.query.sql.Order;
import me.kirillgrachev.query.sql.Select;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;
import java.util.Optional;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Интеграционные тесты исполнения на настоящей in-memory базе H2.
 *
 * <p>В исходной библиотеке интеграционных тестов не было вовсе: проверялся только
 * текст SQL, а исполнение — привязка параметров, закрытие ресурсов, транзакции,
 * сгенерированные ключи — не покрывалось ни разу. Именно поэтому утечки
 * statement'ов и непригодность {@code setObject(i, null)} прожили годы: ни один
 * тест не открывал {@code Connection}.
 */
class SqlIntegrationTest {

    private static final String DB_URL = "jdbc:h2:mem:sql_integration;DB_CLOSE_DELAY=-1";

    private JdbcDataSource dataSource;
    private Sql sql;

    @BeforeEach
    void setUp() throws SQLException {

        dataSource = new JdbcDataSource();
        dataSource.setURL(DB_URL);
        sql = Sql.of(dataSource, Dialect.H2);

        try (Statement st = dataSource.getConnection().createStatement()) {
            // Экранированные имена в DDL: Dialect.H2 экранирует идентификаторы
            // в запросах, и неэкранированное имя в DDL сохранилось бы в верхнем
            // регистре, после чего запросы перестали бы его находить.
            st.execute("DROP TABLE IF EXISTS \"users\"");
            st.execute("CREATE TABLE \"users\" ("
                    + "\"id\" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "\"name\" VARCHAR(64) NOT NULL, "
                    + "\"email\" VARCHAR(128), "
                    + "\"age\" INT, "
                    + "\"status\" VARCHAR(16) NOT NULL)");
        }

        try (var con = dataSource.getConnection()) {
            // Соединение закрывается, но DB_CLOSE_DELAY=-1 сохраняет данные.
            sql.update(Query.insertInto("users")
                    .value("name", "alice").value("email", "alice@example.org")
                    .value("age", 30).value("status", Role.ACTIVE.name()));
            sql.update(Query.insertInto("users")
                    .value("name", "bob").valueNull("email")
                    .value("age", 41).value("status", Role.ACTIVE.name()));
            sql.update(Query.insertInto("users")
                    .value("name", "carol").value("email", "carol@example.org")
                    .valueNull("age").value("status", Role.BLOCKED.name()));
        }

    }

    enum Role {
        ACTIVE, BLOCKED
    }

    @Test
    void selectReturnsMappedRows() {

        List<String> names = sql.queryAll(
                Query.select("name").from("users").orderBy("name"),
                rs -> rs.getString("name"));

        assertEquals(List.of("alice", "bob", "carol"), names);

    }

    @Test
    void queryOneReturnsEmptyOptionalWhenNoRows() {

        Optional<String> found = sql.queryOne(
                Query.select("name").from("users").where("name", "nobody"),
                rs -> rs.getString("name"));

        assertTrue(found.isEmpty());

    }

    @Test
    void queryOneReturnsFirstRowOnly() {

        Optional<String> found = sql.queryOne(
                Query.select("name").from("users").orderBy("name", Order.Direction.DESC),
                rs -> rs.getString("name"));

        assertEquals(Optional.of("carol"), found);

    }

    @Test
    void updateReturnsAffectedRowCount() {

        int affected = sql.update(
                Query.update("users").value("age", 31).where("name", "alice"));

        assertEquals(1, affected);

        Integer age = sql.queryOne(Query.select("age").from("users").where("name", "alice"),
                rs -> rs.getInt("age")).orElseThrow();

        assertEquals(31, age);

    }

    @Test
    void deleteWithConditionRemovesMatchingRowsOnly() {

        int removed = sql.update(Query.deleteFrom("users").where("name", "bob"));

        assertEquals(1, removed);
        assertEquals(2L, countUsers());

    }

    @Test
    void insertReturningKeyGivesGeneratedIdentity() {

        Optional<Long> key = sql.insertReturningKey(
                Query.insertInto("users")
                        .value("name", "dave").value("age", 22).value("status", "ACTIVE"),
                rs -> rs.getLong(1));

        assertTrue(key.isPresent());
        assertTrue(key.get() > 0, "сгенерированный ключ должен быть положительным");

        String name = sql.queryOne(Query.select("name").from("users").where("id", key.get()),
                rs -> rs.getString("name")).orElseThrow();

        assertEquals("dave", name);

    }

    @Test
    void nullParameterIsBoundAsSqlNull() {

        // Исходная библиотека передавала null через setObject(i, null), что часть
        // драйверов отвергает. Здесь null идёт через setNull(i, Types.NULL).
        sql.update(Query.insertInto("users")
                .value("name", "erin").valueNullable("email", null).value("status", "ACTIVE"));

        // SQL NULL, прочитанный маппером, даёт null, а queryOne превращает его в
        // пустой Optional: отличить «строки нет» от «значение NULL» по одному
        // Optional нельзя, и это задокументировано в RowMapper. Наличие самой
        // строки проверяется отдельным запросом.
        Optional<String> email = sql.queryOne(
                Query.select("email").from("users").where("name", "erin"),
                rs -> rs.getString("email"));

        assertTrue(email.isEmpty(), "SQL NULL должен давать пустой Optional");

        boolean rowExists = sql.queryOne(
                Query.select().expr("COUNT(*)").from("users").where("name", "erin"),
                rs -> rs.getLong(1) == 1L).orElse(false);

        assertTrue(rowExists, "строка с NULL в email должна существовать");

        long nullEmails = sql.queryOne(
                Query.select().expr("COUNT(*)").from("users").whereNull("email"),
                rs -> rs.getLong(1)).orElseThrow();

        assertTrue(nullEmails >= 2, "строки с NULL в email не найдены условием IS NULL");

    }

    @Test
    void enumParameterIsBoundAsName() {

        List<String> names = sql.queryAll(
                Query.select("name").from("users").where("status", Role.BLOCKED).orderBy("name"),
                rs -> rs.getString("name"));

        assertEquals(List.of("carol"), names);

    }

    @Test
    void optionalParameterIsUnwrapped() {

        Optional<String> email = Optional.of("alice@example.org");

        long count = sql.queryOne(
                Query.select().expr("COUNT(*)").from("users").where("email", email),
                rs -> rs.getLong(1)).orElseThrow();

        assertEquals(1L, count);

    }

    @Test
    void uuidParameterIsBoundAsString() {

        UUID id = UUID.randomUUID();

        int affected = sql.update(Query.update("users").value("email", id.toString()).where("name", "alice"));

        assertEquals(1, affected);
        assertEquals(id.toString(),
                sql.queryOne(Query.select("email").from("users").where("name", "alice"),
                        rs -> rs.getString("email")).orElseThrow());

    }

    @Test
    void inConditionFiltersBySet() {

        List<String> names = sql.queryAll(
                Query.select("name").from("users")
                        .whereIn("name", List.of("alice", "carol"))
                        .orderBy("name"),
                rs -> rs.getString("name"));

        assertEquals(List.of("alice", "carol"), names);

    }

    @Test
    void orConditionIsExpressibleWithoutRawSql() {

        // В исходной библиотеке OR выражался только сырым SQL: плоский список
        // условий соединялся исключительно через AND.
        List<String> names = sql.queryAll(
                Query.select("name").from("users")
                        .where(Conditions.anyOf(
                                Conditions.eq("name", "alice"),
                                Conditions.eq("name", "bob")))
                        .orderBy("name"),
                rs -> rs.getString("name"));

        assertEquals(List.of("alice", "bob"), names);

    }

    @Test
    void nestedConditionsKeepPrecedence() {

        // (status = ACTIVE AND (name = alice OR name = bob)) — без явных скобок
        // смешивание AND и OR дало бы другой результат.
        long count = sql.queryOne(
                Query.select().expr("COUNT(*)").from("users")
                        .where(Conditions.allOf(
                                Conditions.eq("status", "ACTIVE"),
                                Conditions.anyOf(
                                        Conditions.eq("name", "alice"),
                                        Conditions.eq("name", "bob")))),
                rs -> rs.getLong(1)).orElseThrow();

        assertEquals(2L, count);

    }

    @Test
    void groupByAndHavingWorkAgainstRealData() {

        List<String> blocked = sql.queryAll(
                Query.select("status").expr("COUNT(*)", "cnt").from("users")
                        .groupBy("status")
                        .having("COUNT(*) >= ?", 1)
                        .orderBy("status"),
                rs -> rs.getString("status") + ":" + rs.getInt("cnt"));

        assertEquals(2, blocked.size());

    }

    @Test
    void limitAndOffsetAreApplied() {

        List<String> page = sql.queryAll(
                Query.select("name").from("users").orderBy("name").limit(1).offset(1),
                rs -> rs.getString("name"));

        assertEquals(List.of("bob"), page);

    }

    @Test
    void transactionCommitsWhenBodySucceeds() {

        sql.inTransaction(tx -> {
            tx.update(Query.update("users").value("age", 99).where("name", "alice"));
            tx.update(Query.update("users").value("age", 98).where("name", "bob"));

            return null;
        });

        assertEquals(99, ageOf("alice"));
        assertEquals(98, ageOf("bob"));

    }

    @Test
    void transactionRollsBackOnRuntimeException() {

        assertThrows(IllegalStateException.class, () -> sql.inTransaction(tx -> {
            tx.update(Query.update("users").value("age", 1).where("name", "alice"));
            throw new IllegalStateException("body failed");
        }));

        // Изменение первой строки должно быть откатано вместе со всей транзакцией.
        assertEquals(30, ageOf("alice"));

    }

    @Test
    void transactionRollsBackOnSqlException() {

        QueryException e = assertThrows(QueryException.class, () -> sql.inTransaction(tx -> {
            tx.update(Query.update("users").value("age", 2).where("name", "bob"));
            tx.update(Query.raw("THIS IS NOT SQL"));

            return null;
        }));

        // Сохраняется конкретный код исходной ошибки, а не общий TRANSACTION_FAILED:
        // вызывающей стороне важнее знать, что именно сломалось. В TRANSACTION_FAILED
        // оборачиваются только «сырые» SQLException из тела транзакции.
        assertEquals(ErrorCode.SQL_EXECUTION_FAILED, e.getCode());
        assertEquals(41, ageOf("bob"), "изменение первой строки должно быть откатано");

    }

    @Test
    void transactionSharesOneConnectionBetweenStatements() {

        sql.inTransaction(tx -> {
            tx.update(Query.update("users").value("age", 50).where("name", "carol"));
            tx.update(Query.update("users").value("age", 51).where("name", "carol"));

            return null;
        });

        assertEquals(51, ageOf("carol"));

    }

    @Test
    void selectForUpdateWorksInsideTransaction() {

        String name = sql.inTransaction(tx -> {
            Select select = Query.select("name").from("users").where("id", 1).forUpdate();
            return tx.selectForUpdate(select, rs -> rs.getString("name")).getFirst();
        });

        assertEquals("alice", name);

    }

    @Test
    void invalidSqlIsWrappedWithSqlTextInContext() {

        QueryException e = assertThrows(QueryException.class,
                () -> sql.update(Query.raw("INSERT INTO nonexistent_table VALUES (1)")));

        assertEquals(ErrorCode.SQL_EXECUTION_FAILED, e.getCode());
        assertTrue(String.valueOf(e.getContext().get("sql")).contains("nonexistent_table"),
                "в контексте должен быть текст запроса: " + e.getContext());

    }

    @Test
    void upsertInsertsThenUpdates() {

        sql.update(Query.insertInto("users")
                .value("id", 1000L).value("name", "frank")
                .value("age", 10).value("status", "ACTIVE")
                .onDuplicateKeyUpdateExcept("id"));

        sql.update(Query.insertInto("users")
                .value("id", 1000L).value("name", "frank")
                .value("age", 20).value("status", "ACTIVE")
                .onDuplicateKeyUpdateExcept("id"));

        long count = sql.queryOne(
                Query.select().expr("COUNT(*)").from("users").where("id", 1000L),
                rs -> rs.getLong(1)).orElseThrow();

        assertEquals(1L, count, "upsert должен обновить существующую строку, а не вставить вторую");
        assertEquals(20, sql.queryOne(Query.select("age").from("users").where("id", 1000L),
                rs -> rs.getInt("age")).orElseThrow());

    }

    private int ageOf(String name) {
        return sql.queryOne(Query.select("age").from("users").where("name", name),
                rs -> rs.getInt("age")).orElseThrow();
    }

    private long countUsers() {
        return sql.queryOne(Query.select().expr("COUNT(*)").from("users"),
                rs -> rs.getLong(1)).orElseThrow();
    }

}
